#!/usr/bin/env python3
"""Generate the Kotlin side of the core contract from rust/dspi-ffi.

Reads   rust/dspi-ffi/src/records.rs   (UniFFI records)
        rust/dspi-ffi/src/core.rs      (DspiCore methods)
        rust/dspi-ffi/src/lib.rs       (free functions)
Writes  core-api/src/main/kotlin/se/bofr/dspi/core/CoreTypes.kt    (domain records)
        core-api/src/main/kotlin/se/bofr/dspi/core/DspiCoreApi.kt   (the interface)
        ffi/src/main/kotlin/se/bofr/dspi/ffi/FfiDspiCore.kt         (UniFFI adapter)

The outputs are checked in. `--check` exits 1 if they are stale (CI runs it),
so the Rust FFI surface, the Kotlin interface and the adapter cannot drift.

Type rules (domain side, i.e. everything outside :ffi):
  u8 u16 i32 -> Int     u32 u64 i64 -> Long     f32 -> Float   f64 -> Double
  bool -> Boolean       String -> String        Vec<u8> -> List<Int> (unsigned)
  Vec<u8> named bulk_raw -> ByteArray           Vec<T> -> List<T>
  Result<T> -> T, throws DspiException          Option<Box<dyn L>> -> L?
Names: snake_case -> lowerCamelCase exactly as UniFFI does.
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "rust/dspi-ffi/src"
OUT_TYPES = ROOT / "core-api/src/main/kotlin/se/bofr/dspi/core/CoreTypes.kt"
OUT_API = ROOT / "core-api/src/main/kotlin/se/bofr/dspi/core/DspiCoreApi.kt"
OUT_ADAPTER = ROOT / "ffi/src/main/kotlin/se/bofr/dspi/ffi/FfiDspiCore.kt"
OUT_UNIMPL = ROOT / "core-api/src/main/kotlin/se/bofr/dspi/core/UnimplementedDspiCore.kt"
OUT_CONSTS = ROOT / "core-api/src/main/kotlin/se/bofr/dspi/core/DspiConstants.kt"
CORE_SRC = ROOT / "third_party/DSPi-Console-Linux/core/src"
CONST_FILES = ["protocol.rs", "types.rs", "state.rs", "notify.rs", "stats.rs", "siggen.rs", "rta.rs", "dsp_math.rs", "cs.rs"]

RAW_BYTES = {"bulk_raw"}
FFI = "se.bofr.dspi.ffi.uniffi"
EXCLUDED_FREE_FNS = {"init_logging"}  # adapter-internal
LISTENERS = {"NotifyListener", "RtaListener", "DeviceEvents"}

HEADER = "// GENERATED by tools/gen_kotlin_contract.py from rust/dspi-ffi — do not edit.\n// Regenerate: tools/dev.sh python3 tools/gen_kotlin_contract.py\n"


def camel(s: str) -> str:
    parts = s.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


@dataclass
class Field:
    name: str
    ty: str
    doc: list[str] = field(default_factory=list)


@dataclass
class Record:
    name: str
    fields: list[Field]
    doc: list[str]


@dataclass
class Fn:
    name: str
    params: list[Field]
    ret: str | None
    doc: list[str]
    free: bool


def split_top(s: str, sep: str = ",") -> list[str]:
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [x.strip() for x in out if x.strip()]


def parse_records(text: str) -> list[Record]:
    recs = []
    lines = text.splitlines()
    i = 0
    doc: list[str] = []
    while i < len(lines):
        ln = lines[i].strip()
        if ln.startswith("///"):
            doc.append(ln[3:].strip())
        elif ln.startswith("#["):
            pass
        elif m := re.match(r"pub struct (\w+) \{", ln):
            name, fields, fdoc = m.group(1), [], []
            i += 1
            while lines[i].strip() != "}":
                fl = lines[i].strip()
                if fl.startswith("///"):
                    fdoc.append(fl[3:].strip())
                elif fm := re.match(r"pub (\w+): (.+),$", fl):
                    fields.append(Field(fm.group(1), fm.group(2), fdoc))
                    fdoc = []
                elif fl.startswith("//"):
                    fdoc = []
                i += 1
            recs.append(Record(name, fields, doc))
            doc = []
        else:
            doc = []
        i += 1
    return recs


def parse_fns(text: str, free: bool) -> list[Fn]:
    fns = []
    doc: list[str] = []
    pos = 0
    lines = text.splitlines(keepends=True)
    offsets = []
    acc = 0
    for ln in lines:
        offsets.append(acc)
        acc += len(ln)
    i = 0
    while i < len(lines):
        ln = lines[i].strip()
        if ln.startswith("///"):
            doc.append(ln[3:].strip())
            i += 1
            continue
        if ln.startswith("#["):
            if "uniffi::constructor" in ln:
                doc = ["__ctor__"]
            i += 1
            continue
        if ln.startswith("pub fn "):
            # Collect the signature up to the opening brace.
            sig = ""
            j = i
            while "{" not in lines[j]:
                sig += lines[j].strip() + " "
                j += 1
            sig += lines[j].split("{")[0].strip()
            m = re.match(r"pub fn (\w+)\((.*)\)\s*(?:->\s*(.+?))?\s*$", sig.strip())
            if not m:
                raise SystemExit(f"cannot parse signature: {sig}")
            name, args, ret = m.group(1), m.group(2), m.group(3)
            params = []
            for a in split_top(args):
                if a in ("&self", "self"):
                    continue
                pn, pt = a.split(":", 1)
                params.append(Field(pn.strip(), pt.strip()))
            if doc != ["__ctor__"] and (free or "&self" in args):
                fns.append(Fn(name, params, ret.strip() if ret else None, doc, free))
            doc = []
            i = j + 1
            continue
        doc = []
        i += 1
    _ = pos
    return fns


PRIM = {
    "u8": "Int", "u16": "Int", "i32": "Int", "u32": "Long", "u64": "Long", "i64": "Long",
    "f32": "Float", "f64": "Double", "bool": "Boolean", "String": "String",
}
FFI_PRIM = {
    "u8": "UByte", "u16": "UShort", "i32": "Int", "u32": "UInt", "u64": "ULong", "i64": "Long",
    "f32": "Float", "f64": "Double", "bool": "Boolean", "String": "String",
}


def unwrap_result(t: str) -> tuple[str, bool]:
    m = re.match(r"Result<(.+)>$", t)
    if m:
        return m.group(1), True
    return t, False


def kt(t: str, name: str = "") -> str:
    t = t.strip()
    if t == "()":
        return "Unit"
    if t in PRIM:
        return PRIM[t]
    if t == "Vec<u8>":
        return "ByteArray" if name in RAW_BYTES else "List<Int>"
    if m := re.match(r"Vec<(.+)>$", t):
        return f"List<{kt(m.group(1))}>"
    if m := re.match(r"Option<Box<dyn (\w+)>>$", t):
        return f"{m.group(1)}?"
    return t


# ── expressions converting between domain and UniFFI values ─────────────


def to_ffi(expr: str, t: str, name: str = "") -> str:
    t = t.strip()
    if t in ("u8",):
        return f"{expr}.toUByte()"
    if t == "u16":
        return f"{expr}.toUShort()"
    if t == "u32":
        return f"{expr}.toUInt()"
    if t == "u64":
        return f"{expr}.toULong()"
    if t in PRIM:
        return expr
    if t == "Vec<u8>":
        return f"{expr}.copyOf()" if name in RAW_BYTES else f"ByteArray({expr}.size) {{ {expr}[it].toByte() }}"
    if m := re.match(r"Vec<(.+)>$", t):
        inner = to_ffi("it", m.group(1))
        return expr if inner == "it" else f"{expr}.map {{ {inner} }}"
    if m := re.match(r"Option<Box<dyn (\w+)>>$", t):
        return f"{expr}?.let {{ wrap{m.group(1)}(it) }}"
    return f"{expr}.toFfi()"


def to_dom(expr: str, t: str, name: str = "") -> str:
    t = t.strip()
    if t in ("u8", "u16"):
        return f"{expr}.toInt()"
    if t in ("u32", "u64"):
        return f"{expr}.toLong()"
    if t in PRIM or t == "()":
        return expr
    if t == "Vec<u8>":
        return f"{expr}.copyOf()" if name in RAW_BYTES else f"{expr}.map {{ it.toInt() and 0xFF }}"
    if m := re.match(r"Vec<(.+)>$", t):
        inner = to_dom("it", m.group(1))
        return expr if inner == "it" else f"{expr}.map {{ {inner} }}"
    return f"{expr}.toDomain()"


def kdoc(doc: list[str], indent: str) -> str:
    doc = [d for d in doc if d != "__ctor__"]
    if not doc:
        return ""
    body = "".join(f"{indent} * {d}\n".replace(" * \n", " *\n") for d in doc)
    return f"{indent}/**\n{body}{indent} */\n"


def gen_types(recs: list[Record]) -> str:
    out = [HEADER, "@file:Suppress(\"ArrayInDataClass\")\n\npackage se.bofr.dspi.core\n"]
    for r in recs:
        out.append("\n" + kdoc(r.doc, ""))
        out.append(f"data class {r.name}(\n")
        for f in r.fields:
            out.append(kdoc(f.doc, "    "))
            out.append(f"    val {camel(f.name)}: {kt(f.ty, f.name)},\n")
        out.append(")\n")
    return "".join(out)


def gen_api(fns: list[Fn]) -> str:
    out = [HEADER, """
package se.bofr.dspi.core

/**
 * The DSPi core, 1:1 with `rust/dspi-ffi` (`DspiCore` methods + free
 * functions), which is 1:1 with `dspi_*` in DSPi-Console-Linux `core/src/lib.rs`
 * minus the prefix. `core_spec.md` documents the semantics.
 *
 * Implementations: `FfiDspiCore` (:ffi, the real core over UniFFI) and
 * `FakeDspiCore` (:fake-core, demo mode and tests).
 *
 * Threading: every method may block on USB (≤ 1 s). Callers (the bridge) use
 * ONE serial background dispatcher; never call from the main thread.
 * Failures throw [DspiException]; [DspiException.Refused.status] carries the
 * device's code (see [DspiConstants]).
 *
 * Indices: channel = firmware wire index, output = output index, input =
 * input index — as in the core. App-id mapping is the bridge's job.
 */
interface DspiCoreApi : AutoCloseable {
"""]
    for f in fns:
        ret, throws = unwrap_result(f.ret) if f.ret else ("()", False)
        doc = list(f.doc)
        if f.free:
            doc.append("")
            doc.append("Stateless (a free function in dspi-ffi); needs no device.")
        out.append(kdoc(doc, "    "))
        if throws:
            out.append("    @Throws(DspiException::class)\n")
        params = ", ".join(f"{camel(p.name)}: {kt(p.ty, p.name)}" for p in f.params)
        r = kt(ret)
        out.append(f"    fun {camel(f.name)}({params})" + ("" if r == "Unit" else f": {r}") + "\n\n")
    out[-1] = out[-1].rstrip("\n") + "\n"
    out.append("}\n")
    return "".join(out)


def gen_adapter(recs: list[Record], fns: list[Fn]) -> str:
    out = [HEADER, """
package se.bofr.dspi.ffi

import se.bofr.dspi.core.*
import se.bofr.dspi.ffi.uniffi.DspiCore as FfiCore
import se.bofr.dspi.ffi.uniffi.DspiException as FfiException
import se.bofr.dspi.ffi.uniffi.DeviceEvents as FfiDeviceEvents
import se.bofr.dspi.ffi.uniffi.NotifyListener as FfiNotifyListener
import se.bofr.dspi.ffi.uniffi.RtaListener as FfiRtaListener

/**
 * [DspiCoreApi] over the UniFFI-generated bindings of `libdspi_ffi.so`.
 * Pure delegation + type mapping; all behaviour lives in Rust.
 */
class FfiDspiCore : DspiCoreApi {
    private val core = FfiCore()

    override fun close() = core.close()

    private inline fun <T> call(block: () -> T): T =
        try {
            block()
        } catch (e: FfiException) {
            throw e.toDomain()
        }

    private fun wrapNotifyListener(l: NotifyListener) =
        object : FfiNotifyListener {
            override fun onNotifications() = l.onNotifications()
        }

    private fun wrapRtaListener(l: RtaListener) =
        object : FfiRtaListener {
            override fun onFrame() = l.onFrame()
        }

    private fun wrapDeviceEvents(l: DeviceEvents) =
        object : FfiDeviceEvents {
            override fun onArrived(serial: String) = l.onArrived(serial)

            override fun onDeparted(serial: String) = l.onDeparted(serial)
        }

    companion object {
        init {
            System.loadLibrary("dspi_ffi")
            se.bofr.dspi.ffi.uniffi.initLogging()
        }
    }
"""]
    for f in fns:
        ret, throws = unwrap_result(f.ret) if f.ret else ("()", False)
        params = ", ".join(f"{camel(p.name)}: {kt(p.ty, p.name)}" for p in f.params)
        args = ", ".join(to_ffi(camel(p.name), p.ty, p.name) for p in f.params)
        target = f"{FFI}.{camel(f.name)}({args})" if f.free else f"core.{camel(f.name)}({args})"
        r = kt(ret)
        body = to_dom(target, ret)
        sig = f"    override fun {camel(f.name)}({params})" + ("" if r == "Unit" else f": {r}")
        if throws:
            out.append(f"\n{sig} = call {{ {body} }}\n")
        else:
            out.append(f"\n{sig} = {body}\n")
    out.append("}\n\n// ── Error mapping ──\n\n")
    out.append("""internal fun FfiException.toDomain(): DspiException =
    when (this) {
        is FfiException.Disconnected -> DspiException.Disconnected()
        is FfiException.Transfer -> DspiException.Transfer(msg)
        is FfiException.Refused -> DspiException.Refused(status.toInt())
        is FfiException.InvalidArgument -> DspiException.InvalidArgument(msg)
        is FfiException.Unsupported -> DspiException.Unsupported()
    }
""")
    out.append("\n// ── Record mapping (UniFFI <-> domain) ──\n")
    for r in recs:
        fields_d = ",\n".join(f"        {camel(f.name)} = {to_dom(camel(f.name), f.ty, f.name)}" for f in r.fields)
        fields_f = ",\n".join(f"        {camel(f.name)} = {to_ffi(camel(f.name), f.ty, f.name)}" for f in r.fields)
        out.append(f"\ninternal fun {FFI}.{r.name}.toDomain() =\n    {r.name}(\n{fields_d},\n    )\n")
        out.append(f"\ninternal fun {r.name}.toFfi() =\n    {FFI}.{r.name}(\n{fields_f},\n    )\n")
    return "".join(out)


def gen_unimpl(fns: list[Fn]) -> str:
    out = [HEADER, """
package se.bofr.dspi.core

/**
 * Base [DspiCoreApi] for test doubles: every method throws
 * [NotImplementedError]. Doubles extend it and override what they support,
 * so they keep compiling when the contract grows. Test helper only (no
 * production class extends it).
 */
open class UnimplementedDspiCore : DspiCoreApi {
    override fun close() {}
"""]
    for f in fns:
        ret, _ = unwrap_result(f.ret) if f.ret else ("()", False)
        params = ", ".join(f"{camel(p.name)}: {kt(p.ty, p.name)}" for p in f.params)
        r = kt(ret)
        sig = f"    override fun {camel(f.name)}({params})" + ("" if r == "Unit" else f": {r}")
        out.append(f"\n{sig}: Unit = throw NotImplementedError(\"{f.name}\")\n" if r == "Unit"
                   else f"\n{sig} = throw NotImplementedError(\"{f.name}\")\n")
    out.append("}\n")
    return "".join(out)


def gen_consts() -> str:
    seen: dict[str, str] = {}
    groups: list[tuple[str, list[str]]] = []
    opcodes: list[str] = []
    rx = re.compile(r"^pub const ([A-Z0-9_]+): ([a-z0-9]+) = (.+);")
    for fname in CONST_FILES:
        lines, doc = [], []
        for ln in (CORE_SRC / fname).read_text().splitlines():
            st = ln.strip()
            if ln.startswith("///"):
                doc.append(st[3:].strip())
                continue
            m = rx.match(ln)
            if not m:
                doc = []
                continue
            name, ty, val = m.groups()
            if name in seen:
                raise SystemExit(f"duplicate const {name} in {fname} and {seen[name]}")
            seen[name] = fname
            val = val.replace("<<", "shl")
            if ty in ("f32", "f64"):
                kty, val = ("Float", val + "f") if ty == "f32" else ("Double", val)
            elif ty in ("u64", "i64"):
                kty, val = "Long", val + "L"
            else:
                kty = "Int"
            entry = kdoc(doc, "    ") + f"    const val {name}: {kty} = {val}\n"
            (opcodes if name.startswith("REQ_") else lines).append(entry)
            doc = []
        groups.append((fname, lines))
    out = [HEADER.replace("from rust/dspi-ffi", "from third_party/DSPi-Console-Linux/core/src"), """
@file:Suppress("unused")

package se.bofr.dspi.core

/**
 * Every scalar `pub const` of the pinned core (except `REQ_*`, see [Opcodes]),
 * same names and values. Use these instead of magic numbers.
 */
object DspiConstants {
"""]
    for fname, lines in groups:
        if lines:
            out.append(f"    // ── {fname} ──\n")
            out.extend(lines)
            out.append("\n")
    out[-1] = ""
    out.append("}\n\n/** Vendor request opcodes (`protocol.rs` `REQ_*`), for the monitor and coverage tooling. */\nobject Opcodes {\n")
    out.extend(opcodes)
    out.append("}\n")
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    a = ap.parse_args()
    recs = parse_records((SRC / "records.rs").read_text())
    methods = parse_fns((SRC / "core.rs").read_text(), free=False)
    free = [f for f in parse_fns((SRC / "lib.rs").read_text(), free=True) if f.name not in EXCLUDED_FREE_FNS]
    fns = methods + free
    outputs = {
        OUT_TYPES: gen_types(recs),
        OUT_API: gen_api(fns),
        OUT_ADAPTER: gen_adapter(recs, fns),
        OUT_CONSTS: gen_consts(),
        OUT_UNIMPL: gen_unimpl(fns),
    }
    stale = []
    for path, text in outputs.items():
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run tools/gen_kotlin_contract.py)", file=sys.stderr)
        return 1
    print(f"records={len(recs)} methods={len(methods)} free={len(free)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
